import type { NewWeapon } from '@/db/schema';

/**
 * A pickable weapon template. `data` is spread into `createWeapon` (minus the
 * character link), so its keys mirror the `weapons` table columns.
 *
 * This is static game-reference data — edit the {@link WEAPON_CATALOG} array to
 * add or tune presets; no migration needed. The entries below are SAMPLES to
 * prove the flow end-to-end; replace with the full Prophecy weapon list.
 */
export type WeaponPreset = {
  /** Stable slug (used as list key). */
  id: string;
  category: WeaponCategory;
  /** Subcategory: how many hands the weapon needs. */
  hands: WeaponHands;
  data: Omit<NewWeapon, 'characterId' | 'id'>;
};

export type WeaponCategory = 'Armes tranchantes' |
                              'Armes de choc' | 
                              'Armes contondantes' | 
                              'Armes articulées' |
                              'Armes doubles' |
                              'Armes de corps à corps' |
                              'Armes d\'hast' |
                              'Armes de jet' |
                              'Armes à projectile' |
                              'Armes mécaniques';
export type WeaponHands = 'Une main' | 'Deux mains';

